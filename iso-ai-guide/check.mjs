import assert from 'node:assert/strict';
import {readFileSync,existsSync} from 'node:fs';
import vm from 'node:vm';
import {fileURLToPath} from 'node:url';
import {dirname,resolve} from 'node:path';
const root=dirname(fileURLToPath(import.meta.url));
const read=p=>readFileSync(resolve(root,p),'utf8');
const ctx={window:{}};vm.createContext(ctx);vm.runInContext(read('data.js'),ctx);
const d=ctx.window.ISO_GUIDE;
assert.equal(d.standards.length,3);
const items=d.phases.flatMap(p=>p.items);assert.equal(items.length,12);assert.equal(new Set(items.map(i=>i.id)).size,12);
const ids=d.standards.map(s=>s.id);items.forEach(i=>i.lenses.forEach(id=>assert(ids.includes(id))));
Object.values(d.comparison).forEach(rows=>rows.forEach(r=>assert.equal(r.length,4)));
Object.values(d.examples).forEach(ex=>{assert.equal(ex.length,3);ex.forEach(([id])=>assert(ids.includes(id)));});
d.sources.forEach(s=>assert(/^https:\/\/(www\.iso\.org|webstore\.iec\.ch)\//.test(s.url)));
const h=read('index.html');
assert(!/<script(?![^>]*\ssrc=)/i.test(h));assert(!/\sstyle=|<style|unsafe-inline|unsafe-eval/.test(h));
for(const [,p]of h.matchAll(/(?:src|href)="([^"#:?]+\.(?:css|js|svg))"/g))assert(existsSync(resolve(root,p)),p);
for(const [,id]of h.matchAll(/data-(?:view|open)="([^"]+)"/g))assert(h.includes(`id="${id}"`));
assert(!/innerHTML|insertAdjacentHTML|eval\(|fetch\(/.test(read('app.js')));
console.log('OK: 3 standards; 12 unique actions; comparison, examples, sources, navigation, local assets and CSP checks.');
